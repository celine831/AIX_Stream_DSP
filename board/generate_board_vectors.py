"""Build fixed hardware BIST stimulus and independent golden ROM contents."""
from pathlib import Path
import sys,random
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'sim'))
from golden_model import quantize
COEFFICIENTS=[
    [16384,0,0,0,0,0,0,0],
    [4096]*8,
    [32767,-32768,32767,-32768,32767,-32768,32767,-32768],
    [-4096,2048,8192,16384,-8192,4096,-2048,1024],
]
def generate():
    rng=random.Random(20261013)
    xs=[0,1,-1,3,-3,5,-5,32767,-32768]+[32767]*8+[-32768]*8
    xs += [32767 if i%2 else -32768 for i in range(8)]
    xs += [rng.randint(-32768,32767) for _ in range(64-len(xs))]
    rows=[]
    for bank,coeff in enumerate(COEFFICIENTS):
        history=[0]*8
        for n,x in enumerate(xs):
            history=[x]+history[:-1]
            y=quantize(sum(a*b for a,b in zip(history,coeff)),16,15,1,1)
            rows.append((x,y,int(n==63)))
    text=['// Generated by board/generate_board_vectors.py. Do not edit ROM values by hand.',
          'module board_vector_rom(input wire [7:0] addr, output reg [15:0] sample,',
          '    output reg [15:0] expected, output reg last);',
          '    always @* begin',"        sample=16'h0000; expected=16'h0000; last=1'b0;",'        case(addr)']
    for n,(x,y,last) in enumerate(rows):
        text.append(f"            8'd{n}: begin sample=16'h{x & 65535:04x}; expected=16'h{y & 65535:04x}; last=1'b{last}; end")
    text += ['            default: begin end','        endcase','    end','endmodule',
             'module board_coefficient_rom(input wire [4:0] addr, output reg [15:0] coeff);',
             '    always @* begin',"        coeff=16'h0000;",'        case(addr)']
    for n,x in enumerate(sum(COEFFICIENTS,[])):
        text.append(f"            5'd{n}: coeff=16'h{x & 65535:04x};")
    text += ['            default: begin end','        endcase','    end','endmodule']
    (ROOT/'board/board_vectors.v').write_text('\n'.join(text)+'\n')
    (ROOT/'sim/vectors/board_data.txt').write_text(''.join(f'{x} {y} {last}\n' for x,y,last in rows))
    print('Generated 4 coefficient banks and 256 board golden outputs')
if __name__=='__main__':generate()
